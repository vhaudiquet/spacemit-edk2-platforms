#ifndef _PINCTRL_PCD_CONFIG_H_
#define _PINCTRL_PCD_CONFIG_H_

#define SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN  32

typedef struct {
  UINT8    ControllerId;
  CHAR8    DefaultGroup[SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN];
} SPACEMIT_PINCTRL_CONFIG;

typedef struct {
  UINT16                     Num;
  SPACEMIT_PINCTRL_CONFIG    Data[0];
} SPACEMIT_PINCTRL_CONFIG_ARRAY;

//
// Backward-compatible aliases for existing module code and DSC field access.
//
#define I2C_PINCTRL_GROUP_NAME_MAX_LEN   SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN
#define QSPI_PINCTRL_GROUP_NAME_MAX_LEN  SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN
#define USB_PINCTRL_GROUP_NAME_MAX_LEN   SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN
#define PCIE_PINCTRL_GROUP_NAME_MAX_LEN  SPACEMIT_PINCTRL_GROUP_NAME_MAX_LEN

typedef SPACEMIT_PINCTRL_CONFIG        I2C_PINCTRL_CONFIG;
typedef SPACEMIT_PINCTRL_CONFIG_ARRAY  I2C_PINCTRL_CONFIG_ARRAY;

typedef SPACEMIT_PINCTRL_CONFIG        QSPI_PINCTRL_CONFIG;
typedef SPACEMIT_PINCTRL_CONFIG_ARRAY  QSPI_PINCTRL_CONFIG_ARRAY;

typedef SPACEMIT_PINCTRL_CONFIG        USB_PINCTRL_CONFIG;
typedef SPACEMIT_PINCTRL_CONFIG_ARRAY  USB_PINCTRL_CONFIG_ARRAY;

typedef SPACEMIT_PINCTRL_CONFIG        PCIE_PINCTRL_CONFIG;
typedef SPACEMIT_PINCTRL_CONFIG_ARRAY  PCIE_PINCTRL_CONFIG_ARRAY;

#endif // _PINCTRL_PCD_CONFIG_H_
